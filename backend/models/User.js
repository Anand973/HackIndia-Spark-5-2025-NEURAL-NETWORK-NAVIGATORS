const mongoose = require('mongoose');
console.log("schema is being created")
const userSchema = new mongoose.Schema({
  firstName: {
    type: String,
    required: true,
    trim: true
  },
  lastName: {
    type: String,
    required: true,
    trim: true
  },
  email: {
    type: String,
    required: true,
    unique: true,
    lowercase: true,
    trim: true
  },
  password: {
    type: String,
    required: true
  },
  role: {
    type: String,
    enum: ["",'user' ,'admin']
  }
  
}, {
  timestamps: true
});

module.exports = mongoose.model('User', userSchema);